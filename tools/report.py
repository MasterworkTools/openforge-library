"""Turn sweep.py's dead branches into a report grouped by what would fix them.

Run:  python3 tools/report.py sweep-*.json > coverage-report.md
"""

import collections
import json
import sys

SHORT = ("texture|", "connection|")


def short(v):
    for p in SHORT:
        v = v.replace(p, "")
    return v


def absent_textures(g):
    """Textures no non-base part can be filled in, under any answers."""
    parts = [r for r in g["roles"] if not r.endswith("-base")]
    # The floor has its own texture question beside walls; it only decides
    # the texture's presence in a guide that is about floors.
    parts = [r for r in parts if r != "floor"] or parts
    filled = set()
    for role in parts:
        filled |= set(g["roles"][role]["filled_in"])
    named = set(g["relevant"]) | {
        b["answers"].get("texture") for r in g["roles"].values() for b in r["branches"]
    }
    return {t for t in named if t and t != "*"} - filled


def methods(g):
    return sorted({m for row in g["textures"] for m in row["methods"]})


def groups(data):
    fixes = collections.defaultdict(list)
    for guide, g in data.items():
        absent = absent_textures(g)
        for role, r in g["roles"].items():
            for b in r["branches"]:
                a = b["answers"]
                if a.get("texture") in absent:
                    continue
                # Dual is plain-only by design (Devon, 2026-10-14): its clips need
                # a blank face on both sides, so textured dual bases never exist.
                if "connection|dual" in a.get("base-clips", "").split(","):
                    continue
                why = b["why"]
                if role.endswith("-base"):
                    size = tuple(why["requires"]) if isinstance(why, dict) else ()
                    key = (role, (), size)
                else:
                    tk = "floor-texture" if role == "floor" and "floor-texture" in a else "texture"
                    key = (role, (("texture", a.get(tk) or "*"),), ())
                    a = {k: v for k, v in a.items() if k != tk}
                ctx = {k: v for k, v in a.items() if v != "*" and k not in dict(key[1])}  # noqa: E501
                fixes[key].append((guide, ctx))
    return fixes


def describe(key):
    role, piece, size = key
    bits = [short(v) for k, v in piece]
    if size:
        bits.append("fitting " + "x".join(s.rsplit("|", 1)[1] for s in sorted(size, reverse=True)))
    if role.endswith("-base"):
        return f"{role}: " + (bits[-1] if size else "regardless of size")
    return f"{role}: " + (", ".join(b for b in bits if b != "*") or "any texture")


def main():
    data = {}
    for path in sys.argv[1:]:
        data.update(json.load(open(path)))

    print("# Guide coverage\n")
    print("Generated by tools/sweep.py and tools/report.py from openforge-catalog's fixtures,")
    print("judged by the guide engine itself. Counts are left out on purpose: they drift.\n")

    for guide, g in data.items():
        absent = absent_textures(g)
        offered = set(g["offered"].get("texture", []))
        print(f"## {guide}: textures\n")
        ms = methods(g)
        print("| texture | offered | " + " | ".join(ms) + " |")
        print("|---|---|" + "---|" * len(ms))
        for row in g["textures"]:
            if row["texture"] in absent and row["texture"] not in offered:
                continue
            cells = []
            for m in ms:
                v = row["methods"][m]
                if v["complete"] is not True:
                    cells.append("no" if v["complete"] is None else str(v["complete"]))
                elif "floor" in g["roles"] and v["same_texture_floor"] is not True and guide != "floor":
                    cells.append("yes, other floor")
                else:
                    cells.append("yes")
            print(f"| {short(row['texture'])} | {'yes' if row['texture'] in offered else '**no**'} | " + " | ".join(cells) + " |")
        print(f"\nAbsent (no piece for any part, fine): {', '.join(sorted(short(t) for t in absent)) or 'none'}\n")

    print("## Dead branches, grouped by the piece that would fix them\n")
    print("Each line under a group is the shortest set of answers that cannot be built;")
    print("anything not named there can be answered any way.\n")
    for key, ctxs in sorted(groups(data).items(), key=lambda kv: (kv[0][0], describe(kv[0]))):
        print(f"### {describe(key)}\n")
        # Lines that differ only by texture are one line listing them.
        lines = collections.defaultdict(set)
        for guide, ctx in ctxs:
            rest = tuple(sorted((k, v) for k, v in ctx.items() if k != "texture"))
            # base-clips first: for a base it is the piece, the rest is where
            lines[(guide, rest)].add(ctx.get("texture"))
        for (guide, rest), texs in sorted(lines.items()):
            where = ", ".join(f"{k}={short(v)}" for k, v in rest) or "always"
            texs = sorted(short(t) for t in texs if t)
            print(f"- {guide}: {where}" + (f" — in {', '.join(texs)}" if texs else ""))
        print()


if __name__ == "__main__":
    main()
